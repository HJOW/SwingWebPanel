"""Generates AvifInterTables.java and AvifInterCdfTables.java: the tables of the AV1 specification that the inter decoder (P18-03) needs and that
gen_java_tables.py left out (it generated the tables of the intra decoder).

Usage: python -I gen_inter_tables.py <tables.json> <output directory>

tables.json comes from extract_tables.py; the tables that are already in AvifTables.java / AvifCdfTables.java (found in the output directory) are
not repeated.  The product code and the tests do not need Python or this file; the generated classes are committed.
"""
import json
import re
import sys

tables = json.load(open(sys.argv[1], encoding='utf-8'))
OUT = sys.argv[2]

# names that are already in the classes of the intra decoder
existing = set()
for f in ('AvifTables.java', 'AvifCdfTables.java', 'AvifQmTable.java'):
    try:
        text = open(OUT + '/' + f, encoding='utf-8').read()
    except IOError:
        continue
    existing.update(re.findall(r'<code>([A-Za-z_0-9]+)</code> of the AV1 specification', text))

SKIP_PREFIX = ('Quantizer_Matrix',)
SKIP = set(['Qm_Level', 'Default_Intra_Tx_Type_Set1_Cdf', 'Default_Intra_Tx_Type_Set2_Cdf'])


def const(n):
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', n).upper()


names = [n for n in sorted(tables, key=lambda n: tables[n]['line'])
         if n not in existing and n not in SKIP and not n.startswith(SKIP_PREFIX)]
cdfs = [n for n in names if n.endswith('_Cdf')]
others = [n for n in names if not n.endswith('_Cdf')]


def emit(names, cls, doc_en, doc_ko, path):
    out = []
    out.append('package org.duckdns.hjow.swingwebpanel.media.image.avif;\n')
    out.append('/**\n * %s\n * <p>\n * %s\n */' % (doc_en, doc_ko))
    out.append('final class %s {\n' % cls)
    out.append('    /**\n     * Private constructor: static data holder.\n     * <p>\n     * 비공개 생성자: 정적 자료 보관 클래스이다.\n     */\n    private %s() {\n    }\n' % cls)
    for n in names:
        t = tables[n]
        flat = t['flat']
        dims = 'x'.join(str(d) for d in t['shape'])
        txt = ','.join(str(v) for v in flat)
        chunks = [txt[i:i + 20000] for i in range(0, len(txt), 20000)]
        out.append('    /**\n     * The table <code>%s</code> of the AV1 specification (dimensions %s, flattened in row-major order).\n     * <p>\n     * AV1 규격의 <code>%s</code> 표(차원 %s, 행 우선으로 편 배열).\n     */' % (n, dims, n, dims))
        if len(chunks) == 1:
            out.append('    static final int[] %s = AvifTableData.ints("%s");\n' % (const(n), chunks[0]))
        else:
            out.append('    static final int[] %s = AvifTableData.ints(' % const(n))
            out.append(',\n            '.join('"%s"' % c for c in chunks) + ');\n')
    out.append('}\n')
    open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    return len(names)


src = 'AV1 Bitstream & Decoding Process Specification (https://aomediacodec.github.io/av1-spec/, last modified 2023-07-14, retrieved 2026-11-18)'
srck = 'AV1 Bitstream & Decoding Process Specification(https://aomediacodec.github.io/av1-spec/, 마지막 수정 2023-07-14, 조회일 2026-11-18)'
gen = 'Generated by tests/resources/media/avif/generation/extract_tables.py and gen_inter_tables.py; do not edit by hand.'
genk = 'tests/resources/media/avif/generation/extract_tables.py 와 gen_inter_tables.py 가 생성했으며 손으로 고치지 않는다.'
a = emit(cdfs, 'AvifInterCdfTables', 'The default cumulative distribution tables of the AV1 specification that only the inter coding tools and motion vectors use (%s). %s' % (src, gen),
         '인터 부호화 도구와 움직임 벡터만 쓰는 AV1 규격의 기본 누적 분포 표(%s). %s' % (srck, genk), OUT + '/AvifInterCdfTables.java')
b = emit(others, 'AvifInterTables', 'The constant tables of the AV1 specification that the inter decoder uses: interpolation filters, warp filters, masks, weights and reciprocals (%s). %s' % (src, gen),
         '인터 디코더가 쓰는 AV1 규격의 상수 표: 보간 필터, 워프 필터, 마스크, 가중치, 역수(%s). %s' % (srck, genk), OUT + '/AvifInterTables.java')
print(a, 'inter cdf tables,', b, 'other tables')
print(others)
