package tlsvectors;

import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.io.Writer;
import java.math.BigInteger;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.Signature;
import java.security.interfaces.ECPrivateKey;
import java.security.interfaces.ECPublicKey;
import java.security.interfaces.RSAPublicKey;
import java.security.spec.ECGenParameterSpec;
import java.security.spec.ECPoint;
import java.security.spec.MGF1ParameterSpec;
import java.security.spec.PSSParameterSpec;
import java.util.Random;
import javax.crypto.Cipher;
import javax.crypto.KeyAgreement;
import javax.crypto.spec.IvParameterSpec;
import javax.crypto.spec.SecretKeySpec;

/**
 * Generates cross-check vectors for the TLS module (plan item P32-03) with the standard cryptographic providers of a newer JRE: AES-GCM,
 * ChaCha20-Poly1305, X25519, ECDH and ECDSA on the NIST curves, RSA PKCS #1 v1.5 and RSA-PSS signatures. The module's own code is not
 * used, so the vectors are an independent reference. Run with Java 11 or newer:
 * <code>java -cp build/classes tlsvectors.TlsVectors OUTPUT_FILE</code>. Exit code: 0 = written, 1 = usage error, 2 = an algorithm is
 * missing in the running JRE.
 * <p>
 * TLS 모듈용 대조 벡터를 더 새 JRE 의 표준 암호 공급자로 만든다(계획 P32-03): AES-GCM, ChaCha20-Poly1305, X25519, NIST 곡선의 ECDH 와 ECDSA,
 * RSA PKCS #1 v1.5 와 RSA-PSS 서명. 모듈 자신의 코드를 쓰지 않으므로 벡터는 독립된 기준이다. Java 11 이상으로 실행한다:
 * <code>java -cp build/classes tlsvectors.TlsVectors 출력파일</code>. 종료 코드: 0 = 기록함, 1 = 사용법 오류, 2 = 실행 중인 JRE 에 알고리즘이 없음.
 */
public final class TlsVectors {

    /** The hash names of the signature vectors. / 서명 벡터의 해시 이름. */
    private static final String[] HASHES = { "SHA-256", "SHA-384", "SHA-512" };

    /** The curve names of JCA and of the vector file. / JCA 와 벡터 파일의 곡선 이름. */
    private static final String[][] CURVES = { { "secp256r1", "P-256" }, { "secp384r1", "P-384" }, { "secp521r1", "P-521" } };

    /** The deterministic source of the inputs (keys of the symmetric ciphers, nonces, messages). / 입력(대칭 암호의 키, nonce, 메시지)의 결정적 난수원. */
    private final Random random = new Random(20261128L);

    /** The output. / 출력. */
    private final PrintWriter out;

    /**
     * Creates the generator.
     * <p>
     * 생성기를 만든다.
     *
     * @param out the output / 출력
     */
    private TlsVectors(PrintWriter out) {
        this.out = out;
    }

    /**
     * Entry point.
     * <p>
     * 진입점.
     *
     * @param args the output file / 출력 파일
     * @throws Exception if the file cannot be written / 파일을 쓸 수 없으면
     */
    public static void main(String[] args) throws Exception {
        if (args.length != 1) {
            System.err.println("usage: TlsVectors OUTPUT_FILE");
            System.exit(1);
        }
        Writer w = new OutputStreamWriter(new java.io.FileOutputStream(args[0]), "UTF-8");
        PrintWriter out = new PrintWriter(w);
        try {
            out.print("# Cross-check vectors of the TLS module, generated by tools/tlsvectors with the standard providers of the JRE below.\n");
            out.print("# jre: " + System.getProperty("java.version") + " (" + System.getProperty("java.vendor") + ")\n");
            out.print("# Regenerating gives other key pairs and signatures; every generated file is valid.\n");
            out.print("# Empty values are written as a single minus sign.\n");
            new TlsVectors(out).run();
        } catch (java.security.GeneralSecurityException e) {
            System.err.println("[ERROR] the running JRE lacks an algorithm (use Java 11 or newer): " + e);
            out.close();
            System.exit(2);
        }
        out.close();
    }

    /**
     * Writes all groups of vectors.
     * <p>
     * 모든 벡터 묶음을 쓴다.
     *
     * @throws Exception on a provider failure / 공급자 오류 시
     */
    private void run() throws Exception {
        aead();
        x25519();
        ecdh();
        ecdsa();
        rsa();
    }

    /**
     * Returns pseudo random bytes.
     * <p>
     * 의사 난수 바이트를 반환한다.
     *
     * @param n the length / 길이
     * @return the bytes / 바이트
     */
    private byte[] bytes(int n) {
        byte[] b = new byte[n];
        random.nextBytes(b);
        return b;
    }

    /**
     * Formats bytes as lower case hexadecimal, or a minus sign for no bytes.
     * <p>
     * 바이트를 소문자 16진수로 쓴다. 바이트가 없으면 빼기 기호 하나를 쓴다.
     *
     * @param data the bytes / 바이트
     * @return the text / 문자열
     */
    private static String hex(byte[] data) {
        if (data.length == 0) {
            return "-";
        }
        StringBuilder sb = new StringBuilder(data.length * 2);
        // 바이트마다 두 글자를 쓴다.
        for (int i = 0; i < data.length; i++) {
            sb.append(Character.forDigit((data[i] >> 4) & 15, 16)).append(Character.forDigit(data[i] & 15, 16));
        }
        return sb.toString();
    }

    /**
     * Writes one line of words.
     * <p>
     * 낱말 한 줄을 쓴다.
     *
     * @param words the words / 낱말들
     */
    private void line(String... words) {
        StringBuilder sb = new StringBuilder();
        // 낱말 사이에 공백 하나를 둔다.
        for (int i = 0; i < words.length; i++) {
            if (i > 0) {
                sb.append(' ');
            }
            sb.append(words[i]);
        }
        out.print(sb.append('\n'));
    }

    /**
     * AEAD vectors: <code>gcm|chacha key nonce aad plaintext sealed</code> for many lengths.
     * <p>
     * AEAD 벡터: 여러 길이에 대해 <code>gcm|chacha 키 nonce aad 평문 봉인결과</code>.
     *
     * @throws Exception on a provider failure / 공급자 오류 시
     */
    private void aead() throws Exception {
        int[] lengths = { 0, 1, 15, 16, 17, 31, 32, 33, 63, 64, 65, 127, 128, 129, 255, 256, 257, 1000 };
        // 길이마다 AES-128-GCM, AES-256-GCM, ChaCha20-Poly1305 벡터를 만든다.
        for (int i = 0; i < lengths.length; i++) {
            // 암호 세 가지를 차례로 쓴다.
            for (int kind = 0; kind < 3; kind++) {
                byte[] key = bytes(kind == 0 ? 16 : 32);
                byte[] nonce = bytes(12);
                byte[] aad = bytes(i % 5 == 0 ? 0 : (i * 7) % 40);
                byte[] plain = bytes(lengths[i]);
                Cipher c;
                if (kind < 2) {
                    c = Cipher.getInstance("AES/GCM/NoPadding");
                    // GCMParameterSpec 은 Java 7 의 클래스이므로 이 Java 6 소스에서는 리플렉션으로 만든다.
                    Object spec = Class.forName("javax.crypto.spec.GCMParameterSpec").getConstructor(int.class, byte[].class)
                            .newInstance(Integer.valueOf(128), nonce);
                    c.init(Cipher.ENCRYPT_MODE, new SecretKeySpec(key, "AES"), (java.security.spec.AlgorithmParameterSpec) spec);
                } else {
                    c = Cipher.getInstance("ChaCha20-Poly1305");
                    c.init(Cipher.ENCRYPT_MODE, new SecretKeySpec(key, "ChaCha20"), new IvParameterSpec(nonce));
                }
                // Cipher.updateAAD 는 Java 7 의 메서드이므로 리플렉션으로 부른다.
                Cipher.class.getMethod("updateAAD", byte[].class).invoke(c, new Object[] { aad });
                line(kind < 2 ? "gcm" : "chacha", hex(key), hex(nonce), hex(aad), hex(plain), hex(c.doFinal(plain)));
            }
        }
    }

    /**
     * Returns the last n bytes of an encoded key (the raw value of X25519 keys).
     * <p>
     * 부호화된 키의 마지막 n 바이트(X25519 키의 원시 값)를 반환한다.
     *
     * @param encoded the encoding / 부호화
     * @param n       the number of bytes / 바이트 수
     * @return the tail / 꼬리
     */
    private static byte[] tail(byte[] encoded, int n) {
        byte[] t = new byte[n];
        System.arraycopy(encoded, encoded.length - n, t, 0, n);
        return t;
    }

    /**
     * X25519 vectors: <code>x25519 private public peerPublic shared</code>.
     * <p>
     * X25519 벡터: <code>x25519 개인키 공개키 상대공개키 공유비밀</code>.
     *
     * @throws Exception on a provider failure / 공급자 오류 시
     */
    private void x25519() throws Exception {
        KeyPairGenerator gen = KeyPairGenerator.getInstance("X25519");
        // 키 쌍 열두 개에 대해 합의를 계산한다.
        for (int i = 0; i < 12; i++) {
            KeyPair a = gen.generateKeyPair();
            KeyPair b = gen.generateKeyPair();
            KeyAgreement ka = KeyAgreement.getInstance("X25519");
            ka.init(a.getPrivate());
            ka.doPhase(b.getPublic(), true);
            line("x25519", hex(tail(a.getPrivate().getEncoded(), 32)), hex(tail(a.getPublic().getEncoded(), 32)),
                    hex(tail(b.getPublic().getEncoded(), 32)), hex(ka.generateSecret()));
        }
    }

    /**
     * Formats a non-negative number as hexadecimal.
     * <p>
     * 음이 아닌 수를 16진수로 쓴다.
     *
     * @param v the number / 수
     * @return the text / 문자열
     */
    private static String num(BigInteger v) {
        return v.toString(16);
    }

    /**
     * ECDH vectors: <code>ecdh curve private peerX peerY shared</code>.
     * <p>
     * ECDH 벡터: <code>ecdh 곡선 개인키 상대X 상대Y 공유비밀</code>.
     *
     * @throws Exception on a provider failure / 공급자 오류 시
     */
    private void ecdh() throws Exception {
        // 곡선마다 키 쌍 여섯 개에 대해 합의를 계산한다.
        for (int c = 0; c < CURVES.length; c++) {
            KeyPairGenerator gen = KeyPairGenerator.getInstance("EC");
            gen.initialize(new ECGenParameterSpec(CURVES[c][0]));
            // 키 쌍을 만들어 합의한다.
            for (int i = 0; i < 6; i++) {
                KeyPair a = gen.generateKeyPair();
                KeyPair b = gen.generateKeyPair();
                KeyAgreement ka = KeyAgreement.getInstance("ECDH");
                ka.init(a.getPrivate());
                ka.doPhase(b.getPublic(), true);
                ECPoint w = ((ECPublicKey) b.getPublic()).getW();
                line("ecdh", CURVES[c][1], num(((ECPrivateKey) a.getPrivate()).getS()), num(w.getAffineX()), num(w.getAffineY()),
                        hex(ka.generateSecret()));
            }
        }
    }

    /**
     * Decodes the two integers of a DER encoded ECDSA signature.
     * <p>
     * DER 로 부호화된 ECDSA 서명의 두 정수를 읽는다.
     *
     * @param der the signature / 서명
     * @return r and s / r 과 s
     */
    private static BigInteger[] rs(byte[] der) {
        int at = 1;
        // SEQUENCE 의 길이 옥텟을 건너뛴다(긴 형식이면 한 바이트 더).
        at += (der[at] & 0x80) != 0 ? 1 + (der[at] & 0x7f) : 1;
        BigInteger[] out = new BigInteger[2];
        // INTEGER 두 개를 차례로 읽는다.
        for (int i = 0; i < 2; i++) {
            int len = der[at + 1] & 0xff;
            byte[] v = new byte[len];
            System.arraycopy(der, at + 2, v, 0, len);
            out[i] = new BigInteger(v);
            at += 2 + len;
        }
        return out;
    }

    /**
     * ECDSA vectors: <code>ecdsa curve hash qx qy message r s</code>.
     * <p>
     * ECDSA 벡터: <code>ecdsa 곡선 해시 qx qy 메시지 r s</code>.
     *
     * @throws Exception on a provider failure / 공급자 오류 시
     */
    private void ecdsa() throws Exception {
        // 곡선마다, 해시마다 서명 네 개를 만든다.
        for (int c = 0; c < CURVES.length; c++) {
            KeyPairGenerator gen = KeyPairGenerator.getInstance("EC");
            gen.initialize(new ECGenParameterSpec(CURVES[c][0]));
            // 해시마다 서명한다.
            for (int h = 0; h < HASHES.length; h++) {
                // 키 쌍과 메시지를 바꿔 가며 서명한다.
                for (int i = 0; i < 4; i++) {
                    KeyPair kp = gen.generateKeyPair();
                    byte[] message = bytes(i * 37);
                    Signature s = Signature.getInstance(HASHES[h].replace("-", "") + "withECDSA");
                    s.initSign(kp.getPrivate());
                    s.update(message);
                    BigInteger[] sig = rs(s.sign());
                    ECPoint w = ((ECPublicKey) kp.getPublic()).getW();
                    line("ecdsa", CURVES[c][1], HASHES[h], num(w.getAffineX()), num(w.getAffineY()), hex(message), num(sig[0]), num(sig[1]));
                }
            }
        }
    }

    /**
     * RSA vectors: <code>rsa-pkcs1 hash n e message signature</code> and <code>rsa-pss hash saltLength n e message signature</code> for
     * moduli of 2048, 2049, 3072 and 4096 bits (2049 bits makes the PSS encoding one byte shorter than the modulus).
     * <p>
     * RSA 벡터: 2048, 2049, 3072, 4096비트 법에 대해 <code>rsa-pkcs1 해시 n e 메시지 서명</code> 과 <code>rsa-pss 해시 salt길이 n e 메시지 서명</code>
     * (2049비트에서는 PSS 부호화가 법보다 한 바이트 짧다).
     *
     * @throws Exception on a provider failure / 공급자 오류 시
     */
    private void rsa() throws Exception {
        int[] bits = { 2048, 2049, 3072, 4096 };
        // 법의 길이마다 키 쌍 하나를 만든다.
        for (int b = 0; b < bits.length; b++) {
            KeyPairGenerator gen = KeyPairGenerator.getInstance("RSA");
            gen.initialize(bits[b]);
            KeyPair kp = gen.generateKeyPair();
            RSAPublicKey pub = (RSAPublicKey) kp.getPublic();
            // 해시마다 두 방식으로 서명한다.
            for (int h = 0; h < HASHES.length; h++) {
                int hLen = h == 0 ? 32 : h == 1 ? 48 : 64;
                byte[] message = bytes(b * 50 + h * 9);
                Signature p1 = Signature.getInstance(HASHES[h].replace("-", "") + "withRSA");
                p1.initSign(kp.getPrivate());
                p1.update(message);
                line("rsa-pkcs1", HASHES[h], num(pub.getModulus()), num(pub.getPublicExponent()), hex(message), hex(p1.sign()));
                int[] salts = { hLen, 0, 20 };
                // salt 길이를 바꿔 가며 PSS 서명을 만든다(TLS 는 해시 길이를 쓴다).
                for (int s = 0; s < salts.length; s++) {
                    Signature pss = Signature.getInstance("RSASSA-PSS");
                    pss.setParameter(new PSSParameterSpec(HASHES[h], "MGF1", new MGF1ParameterSpec(HASHES[h]), salts[s], 1));
                    pss.initSign(kp.getPrivate());
                    pss.update(message);
                    line("rsa-pss", HASHES[h], String.valueOf(salts[s]), num(pub.getModulus()), num(pub.getPublicExponent()), hex(message),
                            hex(pss.sign()));
                }
            }
        }
    }
}
