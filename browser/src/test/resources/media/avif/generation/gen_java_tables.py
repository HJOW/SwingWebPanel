import json, re, sys
tables = json.load(open(sys.argv[1]))
OUT = sys.argv[2]
EXCL = ['Default_Mv', 'Comp', 'Ref_Frame', 'Single_Ref', 'Interp', 'Motion', 'Obmc', 'Wedge', 'Warped', 'Subpel', 'Div_Lut', 'Div_Mult', 'Ii_Weights',
        'Quantizer_Matrix', 'Interintra', 'Inter_Intra', 'Inter_Tx', 'Is_Inter', 'Skip_Mode', 'Drl', 'New_Mv', 'Zero_Mv', 'Ref_Mv', 'Quant_Dist', 'tpl',
        'Default_Y_Mode_Cdf', 'Tx_Type_In_Set_Inter', 'Tx_Type_Inter', 'Upscale_Filter_', 'Use_Obmc', 'Default_Inter']
inc = []
for n in sorted(tables, key=lambda n: tables[n]['line']):
    if n.startswith('Quantizer_Matrix') or n in ('Qm_Level',):
        continue
    if any(n.startswith(e) or e in n for e in EXCL if e not in ('Interp',)) and n not in ('Default_Intra_Tx_Type_Set1_Cdf', 'Default_Intra_Tx_Type_Set2_Cdf'):
        continue
    if 'Interp' in n or 'Drl' in n:
        continue
    inc.append(n)
cdfs = [n for n in inc if n.endswith('_Cdf')]
others = [n for n in inc if not n.endswith('_Cdf')]

def const(n):
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', n).upper()
    return s

def emit(names, cls, doc_en, doc_ko, path):
    out = []
    out.append('package org.duckdns.hjow.swingwebpanel.media.image.avif;\n')
    out.append('/**\n * %s\n * <p>\n * %s\n */' % (doc_en, doc_ko))
    out.append('final class %s {\n' % cls)
    out.append('    /**\n     * Private constructor: static data holder.\n     * <p>\n     * 비공개 생성자: 정적 자료 보관 클래스이다.\n     */\n    private %s() {\n    }\n' % cls)
    for n in names:
        t = tables[n]
        flat = t['flat']
        dims = 'x'.join(str(d) for d in t['shape'])
        txt = ','.join(str(v) for v in flat)
        chunks = [txt[i:i + 20000] for i in range(0, len(txt), 20000)]
        out.append('    /**\n     * The table <code>%s</code> of the AV1 specification (dimensions %s, flattened in row-major order).\n     * <p>\n     * AV1 규격의 <code>%s</code> 표(차원 %s, 행 우선으로 편 배열).\n     */' % (n, dims, n, dims))
        if len(chunks) == 1:
            out.append('    static final int[] %s = AvifTableData.ints("%s");\n' % (const(n), chunks[0]))
        else:
            out.append('    static final int[] %s = AvifTableData.ints(' % const(n))
            out.append(',\n            '.join('"%s"' % c for c in chunks) + ');\n')
    out.append('}\n')
    open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    return len(names)

src = 'AV1 Bitstream & Decoding Process Specification (https://aomediacodec.github.io/av1-spec/av1-spec.html, last modified 2023-05-25 12:27 PT, retrieved 2026-11-16)'
srck = 'AV1 Bitstream & Decoding Process Specification(https://aomediacodec.github.io/av1-spec/av1-spec.html, 마지막 수정 2023-05-25 12:27 PT, 조회일 2026-11-16)'
gen = 'Generated by tests/resources/media/avif/generation/extract_tables.py and gen_java_tables.py; do not edit by hand.'
genk = 'tests/resources/media/avif/generation/extract_tables.py 와 gen_java_tables.py 가 생성했으며 손으로 고치지 않는다.'
a = emit(cdfs, 'AvifCdfTables', 'The default cumulative distribution tables of the AV1 specification used by the intra frame decoder (%s). %s' % (src, gen),
         'intra 프레임 디코더가 쓰는 AV1 규격의 기본 누적 분포 표(%s). %s' % (srck, genk), OUT + '/AvifCdfTables.java')
b = emit(others, 'AvifTables', 'The constant tables of the AV1 specification used by the intra frame decoder: scan orders, quantizer lookups, intra prediction weights and filters, loop filter, CDEF and loop restoration parameters, block and transform size conversions (%s). %s' % (src, gen),
         'intra 프레임 디코더가 쓰는 AV1 규격의 상수 표: 스캔 순서, 양자화 조회, 인트라 예측 가중치와 필터, 루프 필터, CDEF, 루프 복원 매개변수, 블록/변환 크기 변환(%s). %s' % (srck, genk), OUT + '/AvifTables.java')
print(a, 'cdf tables,', b, 'other tables')
print([n for n in others])
